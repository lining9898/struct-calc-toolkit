    function tdInterp(table, model, L) {
        // 在指定板型的跨度值之间做线性插值
        // 返回 [Q, Qk, Qq] 或 null（超出范围）
        var data = table[model];
        if (!data) return null;
        var vals = data.vals;
        var spans = [];
        for (var k in vals) { if (vals.hasOwnProperty(k) && vals[k] !== null) spans.push(parseFloat(k)); }
        spans.sort(function(a,b){return a-b;});
        if (spans.length === 0) return null;
        if (L <= spans[0]) {
            // 小于最小跨度，按最小跨度取值（保守）
            return { vals: vals[spans[0]], L1: spans[0], L2: spans[0], interp: false };
        }
        if (L >= spans[spans.length - 1]) {
            // 超出最大跨度，返回null
            return null;
        }
        for (var i = 0; i < spans.length - 1; i++) {
            if (L >= spans[i] && L <= spans[i+1]) {
                var v1 = vals[spans[i]], v2 = vals[spans[i+1]];
                var ratio = (L - spans[i]) / (spans[i+1] - spans[i]);
                var res = [];
                for (var j = 0; j < 3; j++) {
                    res.push(v1[j] + ratio * (v2[j] - v1[j]));
                }
                return { vals: res, L1: spans[i], L2: spans[i+1], interp: true, ratio: ratio };
            }
        }
        return null;
    }

