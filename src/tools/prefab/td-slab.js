                html += '<tr><td>标准组合 [Q<sub>k</sub>]</td><td>' + fmt(Qk_std,2) + '</td><td>' + fmt(sv[1],2) + '</td><td>' + (okQk ? '<span class="badge ok">满足</span>' : '<span class="badge bad">不满足</span>') + '</td></tr>';
